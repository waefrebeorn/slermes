/* JSON-lines harness for the w27_adapter_74f618_p11 gate. */
#include "hermes_json.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "noc_w27_adapter_74f618_p11.h"

static void emit_key(const char *key, json_t *v) {
    char *s = v ? json_dumps(v, 0) : NULL;
    printf("\"%s\":", key);
    if (s) { fputs(s, stdout); free(s); }
    else fputs("null", stdout);
}

int main(void) {
    char line[1048576];
    setvbuf(stdout, NULL, _IONBF, 0);
    while (fgets(line, sizeof(line), stdin)) {
        json_t *in, *out;
        const char *func;
        if (!strchr(line, '{')) continue;
        in = json_parse(line, NULL);
        if (!in) continue;
        func = json_get_str(in, "func", "");
        if (!strcmp(func, "post_kwargs")) out = w27_p11_post_kwargs(in);
        else if (!strcmp(func, "bot_tokens")) out = w27_p11_bot_tokens(in);
        else if (!strcmp(func, "format_mrkdwn")) out = w27_p11_format_mrkdwn(in);
        else if (!strcmp(func, "model_picker_notice")) out = w27_p11_model_picker_notice(in);
        else if (!strcmp(func, "trim_dm_cache")) out = w27_p11_trim_dm_cache(in);
        else if (!strcmp(func, "is_connected")) out = w27_p11_is_connected(in);
        else out = json_string("UNKNOWN_FUNC");
        printf("{");
        emit_key("func", json_string(func));
        fputs(",", stdout);
        emit_key("out", out);
        for (size_t i = 0; i < json_object_size(in); i++) {
            const char *k = json_object_get_key_at(in, i);
            if (!k || !strcmp(k, "func")) continue;
            fputs(",", stdout);
            emit_key(k, json_copy(json_object_get_at(in, i)));
        }
        fputs("}\n", stdout);
        json_free(out);
        json_free(in);
    }
    return 0;
}
