/* JSON-lines harness for the w31_ops_0ed859_p1 gate
 * (webhook payload shaping).
 * One request object per stdin line; one response line carrying the computed
 * "out" plus every input key echoed back. */
#include "hermes_json.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "noc_w31_ops_0ed859_p1.h"

static void emit_key(const char *key, json_t *v) {
    char *s = v ? json_dumps(v, 0) : NULL;
    printf("\"%s\":", key);
    if (s) { fputs(s, stdout); free(s); }
    else fputs("null", stdout);
}

static json_t *dispatch(const json_t *in, const char *func) {
    if (!strcmp(func, "webhook_route_summary"))
        return w31_ops_0ed859_p1_webhook_route_summary(in);
    if (!strcmp(func, "dashboard_route_signature"))
        return w31_ops_0ed859_p1_dashboard_route_signature(in);
    if (!strcmp(func, "webhook_key_in"))
        return w31_ops_0ed859_p1_webhook_key_in(in);
    if (!strcmp(func, "webhook_name_verdict"))
        return w31_ops_0ed859_p1_webhook_name_verdict(in);
    if (!strcmp(func, "webhook_deliver_verdict"))
        return w31_ops_0ed859_p1_webhook_deliver_verdict(in);
    return json_string("UNKNOWN_FUNC");
}

int main(void) {
    char line[262144];
    setvbuf(stdout, NULL, _IONBF, 0);
    while (fgets(line, sizeof(line), stdin)) {
        json_t *in, *out;
        const char *func;
        if (!strchr(line, '{')) continue;
        in = json_parse(line, NULL);
        if (!in) continue;
        func = json_get_str(in, "func", "");
        out = dispatch(in, func);
        printf("{");
        emit_key("func", json_string(func));
        fputs(",", stdout);
        emit_key("out", out);
        for (size_t i = 0; i < json_object_size(in); i++) {
            const char *k = json_object_get_key_at(in, i);
            if (!k || !strcmp(k, "func")) continue;
            fputs(",", stdout);
            emit_key(k, json_copy(json_object_get_at(in, i)));
        }
        fputs("}\n", stdout);
        json_free(out);
        json_free(in);
    }
    return 0;
}
