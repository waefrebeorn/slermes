/* t_port_whtarget.c — differential harness for gate whtarget.
 * Reads {"func":"known","name":...} or {"func":"dispatch","target":<json>},
 * emits {"func":...,"out":bool,...echoed input keys}.
 * Gate: run_one_oracle.sh whtarget oracle_whtarget.py "" \
 *   "src/gateway/webhook_targets.o lib/libjson/json.o"
 */
#include "hermes_json.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "noc_whtarget.h"

static void emit_key(const char *key, json_t *v) {
    char *s = v ? json_dumps(v, 0) : NULL;
    printf("\"%s\":", key);
    if (s) { fputs(s, stdout); free(s); }
    else fputs("null", stdout);
}

int main(void) {
    char line[32768];
    setvbuf(stdout, NULL, _IONBF, 0);
    while (fgets(line, sizeof(line), stdin)) {
        if (!strchr(line, '{')) continue;
        json_t *in = json_parse(line, NULL);
        if (!in) continue;
        const char *func = json_get_str(in, "func", "");
        json_t *out = NULL;
        if (!strcmp(func, "known")) {
            out = json_bool((bool)whtarget_is_known_platform(json_get_str(in, "name", "")));
        } else if (!strcmp(func, "dispatch")) {
            out = json_bool((bool)whtarget_is_dispatchable_target(json_obj_get(in, "target")));
        } else {
            out = json_string("UNKNOWN_FUNC");
        }
        printf("{");
        emit_key("func", json_string(func));
        fputs(",", stdout);
        emit_key("out", out);
        for (size_t i = 0; i < json_object_size(in); i++) {
            const char *k = json_object_get_key_at(in, i);
            if (!k || !strcmp(k, "func")) continue;
            fputs(",", stdout);
            emit_key(k, json_copy(json_object_get_at(in, i)));
        }
        fputs("}\n", stdout);
        json_free(out);
        json_free(in);
    }
    return 0;
}
