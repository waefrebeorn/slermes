/* t_port_slack_adapter_flow7.c -- harness for the Slack plugin-adapter FLOW
 * port, wave 7 (src/gateway/platforms/slack_adapter_flow7.c).
 *
 * Reads JSON lines from stdin: {"func": <name>, "in": {...}}.
 * Emits JSON lines: {"func", "in", "out"} where out captures the decision
 * SEQUENCE (ordered seam events {"name","args","ret"} in "trace"), the final
 * return ("ret") and the state echo ("state"). The echoed "in" is the ORIGINAL
 * input (the oracle re-drives the live reference from it).
 *
 * Scripted I/O lives in in.io: a map seam-name -> result. A result is either
 * a plain JSON value (returned verbatim on every call), a LIST consumed in
 * call order, or {"__script__":true,"ret":<value>,"raise":{...}}.
 * A missing/exhausted script is a fail-closed RuntimeError on both sides.
 *
 * The port .c is #included directly by area-qualified path (self-contained,
 * libjson only; -I src resolves it, avoiding basename collisions).
 */
#include "gateway/platforms/slack_adapter_flow7.c"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef json_t *(*sa7_fn_t)(sa7_ctx_t *, const json_t *);
typedef struct { const char *func; sa7_fn_t fn; } sa7_case_t;

static const sa7_case_t CASES[] = {
    { "__init__", sa7_init },
    { "_add_reaction", sa7_add_reaction },
    { "_agent_view_context_for_event", sa7_agent_view_context_for_event },
    { "_append_link_unfurls", sa7_append_link_unfurls },
    { "_apply_bot_mention", sa7_apply_bot_mention },
    { "_apply_yaml_config", sa7_apply_yaml_config },
    { "_assistant_suggested_prompts", sa7_assistant_suggested_prompts },
    { "_authenticate_workspace", sa7_authenticate_workspace },
    { "_begin_interaction", sa7_begin_interaction },
    { "_bot_authored_thread_root", sa7_bot_authored_thread_root },
    { "_build_message_event", sa7_build_message_event },
    { "_build_model_picker_model_blocks", sa7_build_model_picker_model_blocks },
    { "_build_model_picker_provider_blocks", sa7_build_model_picker_provider_blocks },
    { "_cache_agent_view_context", sa7_cache_agent_view_context },
    { "_cache_assistant_thread_metadata", sa7_cache_assistant_thread_metadata },
    { "_cache_slack_document", sa7_cache_slack_document },
};
#define CASE_COUNT (sizeof(CASES) / sizeof(CASES[0]))

static char *read_line(FILE *f) {
    size_t cap = 4096, len = 0;
    char *buf = malloc(cap);
    if (!buf) return NULL;
    int ch;
    while ((ch = fgetc(f)) != EOF && ch != '\n') {
        if (len + 1 >= cap) {
            cap *= 2;
            char *nb = realloc(buf, cap);
            if (!nb) { free(buf); return NULL; }
            buf = nb;
        }
        buf[len++] = (char)ch;
    }
    if (ch == EOF && len == 0) { free(buf); return NULL; }
    buf[len] = '\0';
    return buf;
}

int main(void) {
    setvbuf(stdout, NULL, _IOLBF, 0);
    json_t *empty_args = json_object();
    char *line;
    while ((line = read_line(stdin)) != NULL) {
        if (!line[0]) { free(line); continue; }
        json_t *rec = json_parse(line, NULL);
        free(line);
        if (!rec || rec->type != JSON_OBJECT) { if (rec) json_free(rec); continue; }
        const char *func = json_get_str(rec, "func", "");
        json_t *in = json_obj_get(rec, "in");
        if (!in || in->type != JSON_OBJECT) in = NULL;
        json_t *out = json_object();

        const sa7_case_t *tc = NULL;
        for (size_t i = 0; i < CASE_COUNT; i++) {
            if (strcmp(CASES[i].func, func) == 0) { tc = &CASES[i]; break; }
        }
        if (!tc) {
            json_set(out, "error", json_string("unknown func"));
        } else {
            json_t *args = in ? json_obj_get(in, "args") : NULL;
            if (!args || args->type != JSON_OBJECT) args = NULL;
            json_t *state = in ? json_obj_get(in, "state") : NULL;
            sa7_ctx_t ctx;
            ctx.state = (state && state->type == JSON_OBJECT) ? json_copy(state) : json_object();
            ctx.io = in ? json_obj_get(in, "io") : NULL;
            ctx.cursors = json_object();
            ctx.trace = json_array();
            json_t *ret = tc->fn(&ctx, args ? args : empty_args);
            json_set(out, "ret", ret ? ret : json_null());
            json_set(out, "trace", ctx.trace);
            json_set(out, "state", ctx.state);
            json_free(ctx.cursors);
        }
        json_t *echo = json_object();
        json_set(echo, "func", json_string(func));
        json_set(echo, "in", in ? json_copy(in) : json_null());
        json_set(echo, "out", out);
        char *s = json_serialize(echo);
        if (s) { printf("%s\n", s); fflush(stdout); free(s); }
        json_free(echo);
        json_free(rec);
    }
    json_free(empty_args);
    return 0;
}
