/* JSON-lines harness for the w22_crypto_2e84d7 gate.
 * One request object per stdin line; one response object per line carrying the
 * computed "out" plus every input key echoed back. Missing keys never crash. */
#include "hermes_json.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "noc_w22_crypto_2e84d7.h"

static void emit_key(const char *key, json_t *v) {
    char *s = v ? json_dumps(v, 0) : NULL;
    printf("\"%s\":", key);
    if (s) { fputs(s, stdout); free(s); }
    else fputs("null", stdout);
}

int main(void) {
    char line[262144];
    setvbuf(stdout, NULL, _IOFBF, 1u << 20);
    while (fgets(line, sizeof(line), stdin)) {
        json_t *in, *out = NULL;
        const char *func;
        if (!strchr(line, '{')) continue;
        in = json_parse(line, NULL);
        if (!in) continue;
        func = json_get_str(in, "func", "");
        if (!strcmp(func, "bind_key")) {
            out = w22_crypto_2e84d7_bind_key_shape();
        } else if (!strcmp(func, "b64_encode_hex")) {
            out = w22_crypto_2e84d7_b64_encode_hex(json_get_str(in, "hex", NULL));
        } else if (!strcmp(func, "b64_decode_len")) {
            out = w22_crypto_2e84d7_b64_decode_len(json_get_str(in, "text", ""));
        } else if (!strcmp(func, "decrypt")) {
            out = w22_crypto_2e84d7_decrypt(json_get_str(in, "enc", ""),
                                            json_get_str(in, "key", ""));
        } else {
            out = json_string("UNKNOWN_FUNC");
        }
        printf("{");
        emit_key("func", json_string(func));
        fputs(",", stdout);
        emit_key("out", out);
        for (size_t i = 0; i < json_object_size(in); i++) {
            const char *k = json_object_get_key_at(in, i);
            if (!k || !strcmp(k, "func")) continue;
            fputs(",", stdout);
            emit_key(k, json_copy(json_object_get_at(in, i)));
        }
        fputs("}\n", stdout);
        fflush(stdout);
        json_free(out);
        json_free(in);
    }
    return 0;
}
