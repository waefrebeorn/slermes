/* JSON-lines harness for the w32_chatws_cd49ef_p2 gate.
 * One request object per stdin line; one response line carrying the computed
 * "out" plus every input key echoed back. */
#include "hermes_json.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "noc_w32_chatws_cd49ef_p2.h"

static void emit_key(const char *key, json_t *v) {
    char *s = v ? json_dumps(v, 0) : NULL;
    printf("\"%s\":", key);
    if (s) { fputs(s, stdout); free(s); }
    else fputs("null", stdout);
}

int main(void) {
    char line[1048576];
    setvbuf(stdout, NULL, _IOFBF, 1u << 20);
    while (fgets(line, sizeof(line), stdin)) {
        json_t *in, *out;
        const char *func;
        if (!strchr(line, '{')) continue;
        in = json_parse(line, NULL);
        if (!in) continue;
        func = json_get_str(in, "func", "");
        if (!strcmp(func, "sidecar_gate")) {
            out = w32_chatws_cd49ef_p2_sidecar_gate(in);
        } else if (!strcmp(func, "event_state")) {
            out = w32_chatws_cd49ef_p2_event_state(in);
        } else if (!strcmp(func, "lease_holder")) {
            out = w32_chatws_cd49ef_p2_lease_holder(in);
        } else if (!strcmp(func, "broadcast")) {
            out = w32_chatws_cd49ef_p2_broadcast(in);
        } else if (!strcmp(func, "marker_state")) {
            out = w32_chatws_cd49ef_p2_marker_state(in);
        } else {
            out = json_string("UNKNOWN_FUNC");
        }
        printf("{");
        emit_key("func", json_string(func));
        fputs(",", stdout);
        emit_key("out", out);
        for (size_t i = 0; i < json_object_size(in); i++) {
            const char *k = json_object_get_key_at(in, i);
            if (!k || !strcmp(k, "func")) continue;
            fputs(",", stdout);
            emit_key(k, json_copy(json_object_get_at(in, i)));
        }
        fputs("}\n", stdout);
        fflush(stdout);
        json_free(out);
        json_free(in);
    }
    return 0;
}
