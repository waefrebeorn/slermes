/* ── 10. _mark_completions_delivered_locked: inflight->delivered + trim ── */
/* PoP: rnf_mark_completions_delivered_locked @ gateway/run_notifications.py:_mark_completions_delivered_locked */
void rnf_mark_completions_delivered_locked(json_t *state, const json_t *identities) {
    json_t *inflight = json_obj_get(state, "inflight");
    json_t *delivered = json_obj_get(state, "delivered");
    long long retention = (long long)json_get_num(state, "retention", 0);
    size_t n = gflow_is_arr(identities) ? json_len(identities) : 0;
    for (size_t i = 0; i < n; i++) {
        const json_t *id = json_get(identities, i);
        rnf_set_discard(inflight, id);
        char *key = rnf_idkey(id);
        json_set(delivered, key, json_null()); /* existing key keeps position */
        free(key);
    }
    /* popitem(last=False): trim the OLDEST delivered identities */
    while (delivered && delivered->type == JSON_OBJECT
           && (long long)delivered->c.count > retention && delivered->c.count > 0) {
        json_obj_del(delivered, delivered->c.keys[0]);
    }
}

