/* ── 14. _settle_durable_claim: kind->op dispatch, best-effort ── */
/* PoP: rnf_settle_durable_claim @ gateway/run_notifications.py:_settle_durable_claim */
void rnf_settle_durable_claim(const char *kind, const char *delegation_id,
                              const char *claim_id, const rnf_io_t *io) {
    static const struct { const char *kind, *fn, *fail; } ops[4] = {
        { "drop", "drop_completion_delivery", "Could not drop durable completion claim" },
        { "release", "release_completion_delivery", "Could not release durable completion claim" },
        { "defer", "defer_completion_delivery", "Could not defer unadmitted completion claim" },
        { "complete", "complete_completion_delivery", "Could not acknowledge durable completion claim" },
    };
    const char *fn = NULL, *fail = NULL;
    for (int i = 0; i < 4; i++) {
        if (kind && strcmp(kind, ops[i].kind) == 0) { fn = ops[i].fn; fail = ops[i].fail; break; }
    }
    if (!fn) {
        /* _DURABLE_CLAIM_OPS[kind] raises KeyError OUTSIDE the try */
        json_t *kn = json_string(kind ? kind : "");
        char *rp = rnf_repr(kn);
        json_free(kn);
        rnf_raise("KeyError", rp);
        free(rp);
        return;
    }
    json_t *args = json_object();
    json_set(args, "delegation_id", json_string(delegation_id ? delegation_id : ""));
    json_set(args, "claim_id", json_string(claim_id ? claim_id : ""));
    json_t *r = rnf_call(io, fn, args);
    json_free(r);
    if (rnf_pending) {
        char *msg = rnf_swallow_msg();
        if (!msg) return; /* BaseException propagates */
        free(msg);
        rnf_log(io, strcmp(kind, "complete") == 0 ? 30 : 10, fail, json_array());
    }
}
