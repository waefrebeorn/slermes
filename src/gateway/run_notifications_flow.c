/* ── 16. _drain_watch_notifications: admission/suppression/backoff chain ──
 * Seams (in live call order): drain_gateway_watch_events, monotonic +
 * queue_put (backoff hold), completion_event_scope_or_refuse, scope_enter /
 * scope_exit (the async-with block, fired on EVERY exit path incl. continue
 * and exception unwind), should_surface_notification,
 * load_background_notifications_mode, deliver_heartbeat (heartbeat branch)
 * OR format_gateway_process_notification + inject_watch_notification, then
 * the REAL _requeue_refused_watch_event (itself seaming _refusal_retry_at +
 * queue_put) when delivered IS False. */
/* PoP: rnf_drain_watch_notifications @ gateway/run_notifications.py:_drain_watch_notifications */
void rnf_drain_watch_notifications(const char *queue_id, const rnf_io_t *io) {
    json_t *a = json_object();
    json_set(a, "queue", json_string(queue_id ? queue_id : "q"));
    json_t *events = rnf_call(io, "drain_gateway_watch_events", a);
    if (rnf_pending) { json_free(events); return; }
    if (!events) return;
    if (events->type != JSON_ARRAY) {
        char msg[128];
        snprintf(msg, sizeof(msg), "'%s' object is not iterable", rnf_typename(events));
        rnf_raise("TypeError", msg);
        json_free(events);
        return;
    }
    for (size_t i = 0; i < events->c.count; i++) {
        json_t *evt = json_copy(events->c.items[i]);
        const json_t *nra = gflow_obj_get(evt, "_watch_next_retry_at");
        if (nra && nra->type != JSON_NULL) {
            /* monotonic only evaluated when next_retry_at is not None */
            json_t *now = rnf_call(io, "monotonic", json_object());
            if (rnf_pending) { json_free(now); json_free(evt); goto out; }
            bool ok;
            bool hold = rnf_gt(nra, now, &ok);
            json_free(now);
            if (!ok) { json_free(evt); goto out; }
            if (hold) {
                json_t *pa = json_object();
                json_set(pa, "evt", json_copy(evt));
                json_t *pr = rnf_call(io, "queue_put", pa);
                json_free(pr);
                if (rnf_pending) { json_free(evt); goto out; }
                json_free(evt);
                continue;
            }
        }
        a = json_object();
        json_set(a, "evt", json_copy(evt));
        json_set(a, "label", json_string("watch notification"));
        json_t *scope = rnf_call(io, "completion_event_scope_or_refuse", a);
        if (rnf_pending) { json_free(scope); json_free(evt); goto out; }
        if (!scope) { json_free(evt); continue; } /* refused: only this event */
        const char *sid = gflow_str(scope);
        a = json_object();
        json_set(a, "id", json_string(sid ? sid : ""));
        json_t *er = rnf_call(io, "scope_enter", a);
        json_free(er);
        if (rnf_pending) { json_free(scope); json_free(evt); goto out; }

        json_t *delivered = NULL;
        bool skip_requeue = false;

        a = json_object();
        json_set(a, "evt", json_copy(evt));
        json_t *surface = rnf_call(io, "should_surface_notification", a);
        if (rnf_pending) goto scope_exit;
        if (!gflow_truth(surface)) { json_free(surface); skip_requeue = true; goto scope_exit; }
        json_free(surface);

        json_t *mode = rnf_call(io, "load_background_notifications_mode", json_object());
        if (rnf_pending) goto scope_exit;
        const char *ms = gflow_str(mode);
        bool off = ms && strcmp(ms, "off") == 0;
        json_free(mode);
        if (off) { skip_requeue = true; goto scope_exit; }

        const char *tys = gflow_str(gflow_obj_get(evt, "type"));
        if (tys && strcmp(tys, "heartbeat") == 0) {
            a = json_object();
            json_set(a, "evt", json_copy(evt));
            delivered = rnf_call(io, "deliver_heartbeat", a);
            if (rnf_pending) goto scope_exit;
        } else {
            a = json_object();
            json_set(a, "evt", json_copy(evt));
            json_t *synth = rnf_call(io, "format_gateway_process_notification", a);
            if (rnf_pending) goto scope_exit;
            if (!gflow_truth(synth)) { json_free(synth); skip_requeue = true; goto scope_exit; }
            a = json_object();
            json_set(a, "synth_text", json_copy(synth));
            json_set(a, "evt", json_copy(evt));
            json_free(synth);
            delivered = rnf_call(io, "inject_watch_notification", a);
            if (rnf_pending) {
                char *msg = rnf_swallow_msg();
                if (!msg) goto scope_exit; /* BaseException: exit then propagate */
                free(msg);
                rnf_log(io, 40, "Watch notification injection error", json_array());
                delivered = json_bool(false);
            }
        }

scope_exit:
        a = json_object();
        json_set(a, "id", json_string(sid ? sid : ""));
        er = rnf_call(io, "scope_exit", a);
        json_free(er);
        json_free(scope);
        if (rnf_pending) { json_free(delivered); json_free(evt); goto out; }
        /* delivered IS False (identity, not truthiness): None never requeues */
        if (!skip_requeue && delivered && delivered->type == JSON_BOOL && !delivered->bool_val) {
            rnf_requeue_refused_watch_event(evt, io);
            if (rnf_pending) { json_free(delivered); json_free(evt); goto out; }
        }
        json_free(delivered);
        json_free(evt);
    }
out:
    json_free(events);
}
