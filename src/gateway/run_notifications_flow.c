/*
 * run_notifications_flow.c — gateway notification-delivery FLOW cores and
 * leaves of gateway/run_notifications.py (GatewayNotificationsMixin + module
 * functions).
 *
 * Ports the DECISION sequences: notice-dedupe key projection, refusal-backoff
 * scheduling, completion-identity dedup ordering (inflight/delivered sets with
 * retention trim), durable-claim settlement dispatch, watch-metadata platform
 * projection branches, and the watch-drain admission/suppression chain. All
 * live I/O (transport resolution, identity probes, queue puts, scope binding,
 * heartbeat/injection delivery, logging, clock/backoff) enters through one
 * universal seam; the cores themselves perform no I/O.
 *
 * Seam contract (rnf_io_t):
 *   call(ctx, name, args) — args is a BORROWED json object owned by the port
 *     (the port frees it after the call; the seam must NOT free it). Returns
 *     a NEW json_t the port owns: NULL == Python None, a JSON null node is
 *     never returned for None, and {"__raise__": cls, "message": msg} models
 *     a raised exception (parked on the rnf_pending channel).
 *   log(ctx, level, fmt, args) — args BORROWED (port frees); fmt is the raw
 *     format string, args the raw argument array (no printf formatting),
 *     matching the oracle's recording logger. exc_info unmodeled.
 *
 * Exception model: except Exception sites swallow plain raises but pass the
 * BaseException kinds (SystemExit/KeyboardInterrupt/GeneratorExit/
 * CancelledError) through. Functions with no try park ANY raise. The harness
 * resets rnf_pending before each call and reads it after.
 *
 * Fixture scope: str()/repr() coercions see strings, integral numbers, bools
 * and None only (libjson stores every number as a double; integral doubles
 * format int-like, matching json.loads ints). Identity tuples are all-string
 * so the inflight set sort is elementwise-comparable on both sides.
 */
#ifndef _GNU_SOURCE
#define _GNU_SOURCE
#endif
#include "gateway_lifecycle_flow.h"

#define RNF_INTERNAL_FOOTER "[INTERNAL NOTIFICATION \xe2\x80\x94 generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]"

/* ── universal seam + raise channel ── */
typedef struct rnf_io {
    void *ctx;
    json_t *(*call)(void *ctx, const char *name, const json_t *args);
    void (*log)(void *ctx, int level, const char *fmt, const json_t *args);
} rnf_io_t;

static json_t *rnf_pending; /* parked raise spec; harness-owned reset/read */

static bool rnf_is_base_exc(const char *cls) {
    return cls && (strcmp(cls, "SystemExit") == 0
                   || strcmp(cls, "KeyboardInterrupt") == 0
                   || strcmp(cls, "GeneratorExit") == 0
                   || strcmp(cls, "CancelledError") == 0);
}

static void rnf_park(json_t *spec /* owned */) {
    if (rnf_pending) json_free(rnf_pending);
    rnf_pending = spec;
}

static void rnf_raise(const char *cls, const char *msg) {
    json_t *s = json_object();
    json_set(s, "__raise__", json_string(cls));
    json_set(s, "message", json_string(msg ? msg : ""));
    rnf_park(s);
}

/* except Exception site: swallow a plain raise, returning its malloc'd
 * message; NULL when nothing is parked or a BaseException must propagate. */
static char *rnf_swallow_msg(void) {
    if (!rnf_pending) return NULL;
    if (rnf_is_base_exc(json_get_str(rnf_pending, "__raise__", ""))) return NULL;
    char *m = strdup(json_get_str(rnf_pending, "message", ""));
    json_free(rnf_pending);
    rnf_pending = NULL;
    return m;
}

/* args OWNED by this helper (freed after the seam borrows it). */
static json_t *rnf_call(const rnf_io_t *io, const char *name, json_t *args) {
    json_t *r = NULL;
    if (io && io->call) r = io->call(io->ctx, name, args);
    else rnf_raise("RuntimeError", "seam not installed");
    json_free(args);
    if (r && r->type == JSON_OBJECT && json_obj_get(r, "__raise__")) {
        rnf_park(r);
        return NULL;
    }
    return r;
}

static void rnf_log(const rnf_io_t *io, int level, const char *fmt, json_t *args /* owned */) {
    if (io && io->log) io->log(io->ctx, level, fmt, args);
    json_free(args);
}

/* ── Python string semantics ── */

/* UTF-8 White_Space set used by str.strip()/rstrip() (no argument). */
static bool rnf_is_ws(unsigned int cp) {
    return (cp >= 0x09 && cp <= 0x0D) || cp == 0x20 || cp == 0x85 || cp == 0xA0
           || cp == 0x1680 || (cp >= 0x2000 && cp <= 0x200A)
           || cp == 0x2028 || cp == 0x2029 || cp == 0x202F || cp == 0x205F
           || cp == 0x3000;
}

/* Decode the codepoint starting at s[i]; returns its byte length (1 on a
 * stray continuation byte, treating it as one byte). */
static size_t rnf_cp_len(const char *s, size_t len, size_t i, unsigned int *cp) {
    unsigned char c = (unsigned char)s[i];
    if (c < 0x80) { *cp = c; return 1; }
    size_t n = 0; unsigned int v = 0;
    if ((c & 0xE0) == 0xC0) { n = 2; v = c & 0x1F; }
    else if ((c & 0xF0) == 0xE0) { n = 3; v = c & 0x0F; }
    else if ((c & 0xF8) == 0xF0) { n = 4; v = c & 0x07; }
    else { *cp = c; return 1; }
    if (i + n > len) { *cp = c; return 1; }
    for (size_t k = 1; k < n; k++) {
        unsigned char cc = (unsigned char)s[i + k];
        if ((cc & 0xC0) != 0x80) { *cp = c; return 1; }
        v = (v << 6) | (cc & 0x3F);
    }
    *cp = v;
    return n;
}

static char *rnf_strip(const char *s) {
    if (!s) s = "";
    size_t len = strlen(s), a = 0, b = len;
    while (a < b) {
        unsigned int cp; size_t n = rnf_cp_len(s, b, a, &cp);
        if (!rnf_is_ws(cp)) break;
        a += n;
    }
    while (b > a) {
        /* find start of the last codepoint before b */
        size_t i = b - 1;
        while (i > a && ((unsigned char)s[i] & 0xC0) == 0x80) i--;
        unsigned int cp; size_t n = rnf_cp_len(s, b, i, &cp);
        if (!rnf_is_ws(cp) || i + n != b) break;
        b = i;
    }
    char *r = malloc(b - a + 1);
    memcpy(r, s + a, b - a);
    r[b - a] = '\0';
    return r;
}

static char *rnf_rstrip(const char *s) {
    if (!s) s = "";
    size_t len = strlen(s), b = len;
    while (b > 0) {
        size_t i = b - 1;
        while (i > 0 && ((unsigned char)s[i] & 0xC0) == 0x80) i--;
        unsigned int cp; size_t n = rnf_cp_len(s, b, i, &cp);
        if (!rnf_is_ws(cp) || i + n != b) break;
        b = i;
    }
    char *r = malloc(b + 1);
    memcpy(r, s, b);
    r[b] = '\0';
    return r;
}

/* ASCII lower (fixture platform names are ASCII; Python lower is Unicode). */
static char *rnf_lower(const char *s) {
    char *r = strdup(s ? s : "");
    for (char *p = r; *p; p++)
        if (*p >= 'A' && *p <= 'Z') *p += 32;
    return r;
}

/* Python repr for the fixture value domain: str / integral number / bool /
 * None. Quote pick: single, unless the string contains ' and no " . */
static char *rnf_repr(const json_t *v) {
    if (!v || v->type == JSON_NULL) return strdup("None");
    if (v->type == JSON_BOOL) return strdup(v->bool_val ? "True" : "False");
    if (v->type == JSON_NUMBER) {
        char buf[64];
        double d = v->num_val;
        if (d == (double)(long long)d) snprintf(buf, sizeof(buf), "%lld", (long long)d);
        else snprintf(buf, sizeof(buf), "%.17g", d);
        return strdup(buf);
    }
    if (v->type != JSON_STRING) {
        char *s = json_serialize(v);
        return s ? s : strdup("");
    }
    const char *s = v->str_val ? v->str_val : "";
    bool has_sq = strchr(s, '\'') != NULL, has_dq = strchr(s, '"') != NULL;
    char q = (has_sq && !has_dq) ? '"' : '\'';
    size_t cap = strlen(s) * 4 + 3, len = 0;
    char *r = malloc(cap);
    r[len++] = q;
    for (const unsigned char *p = (const unsigned char *)s; *p; p++) {
        unsigned char c = *p;
        if (c == '\\') { r[len++] = '\\'; r[len++] = '\\'; }
        else if (c == (unsigned char)q) { r[len++] = '\\'; r[len++] = (char)c; }
        else if (c == '\n') { r[len++] = '\\'; r[len++] = 'n'; }
        else if (c == '\r') { r[len++] = '\\'; r[len++] = 'r'; }
        else if (c == '\t') { r[len++] = '\\'; r[len++] = 't'; }
        else if (c < 0x20 || c == 0x7F) {
            len += (size_t)snprintf(r + len, cap - len, "\\x%02x", c);
        }
        else r[len++] = (char)c;
    }
    r[len++] = q;
    r[len] = '\0';
    return r;
}

/* Python type name for TypeError messages (integral double == int). */
static const char *rnf_typename(const json_t *v) {
    if (!v || v->type == JSON_NULL) return "NoneType";
    switch (v->type) {
        case JSON_BOOL: return "bool";
        case JSON_NUMBER:
            return v->num_val == (double)(long long)v->num_val ? "int" : "float";
        case JSON_STRING: return "str";
        case JSON_ARRAY: return "list";
        case JSON_OBJECT: return "dict";
        default: return "object";
    }
}

static bool rnf_numeric(const json_t *v) {
    return v && (v->type == JSON_NUMBER || v->type == JSON_BOOL);
}
static double rnf_numval(const json_t *v) {
    return v->type == JSON_BOOL ? (v->bool_val ? 1.0 : 0.0) : v->num_val;
}

/* a + b with the operand-type TypeError when either side is non-numeric. */
static json_t *rnf_add(const json_t *a, const json_t *b) {
    if (rnf_numeric(a) && rnf_numeric(b))
        return json_number(rnf_numval(a) + rnf_numval(b));
    char msg[160];
    snprintf(msg, sizeof(msg), "unsupported operand type(s) for +: '%s' and '%s'",
             rnf_typename(a), rnf_typename(b));
    rnf_raise("TypeError", msg);
    return NULL;
}

/* a > b; *ok false (TypeError parked) for non-comparable operand types. */
static bool rnf_gt(const json_t *a, const json_t *b, bool *ok) {
    *ok = true;
    if (rnf_numeric(a) && rnf_numeric(b)) return rnf_numval(a) > rnf_numval(b);
    if (a && b && a->type == JSON_STRING && b->type == JSON_STRING)
        return strcmp(a->str_val ? a->str_val : "", b->str_val ? b->str_val : "") > 0;
    char msg[160];
    snprintf(msg, sizeof(msg), "'>' not supported between instances of '%s' and '%s'",
             rnf_typename(a), rnf_typename(b));
    rnf_raise("TypeError", msg);
    *ok = false;
    return false;
}

/* int(v) for the `int(x or 0)` sites: NULL models the falsy->0 fallback.
 * Returns false with ValueError/TypeError parked on a bad string/other. */
static bool rnf_py_int(const json_t *v, long long *out) {
    if (!v || v->type == JSON_NULL) { *out = 0; return true; }
    if (v->type == JSON_BOOL) { *out = v->bool_val ? 1 : 0; return true; }
    if (v->type == JSON_NUMBER) { *out = (long long)v->num_val; return true; }
    if (v->type == JSON_STRING) {
        const char *s = v->str_val ? v->str_val : "";
        while (*s == ' ' || *s == '\t' || *s == '\n' || *s == '\r' || *s == '\v' || *s == '\f') s++;
        const char *e = s + strlen(s);
        while (e > s && (e[-1] == ' ' || e[-1] == '\t' || e[-1] == '\n' || e[-1] == '\r' || e[-1] == '\v' || e[-1] == '\f')) e--;
        const char *p = s;
        bool neg = false;
        if (p < e && (*p == '+' || *p == '-')) { neg = *p == '-'; p++; }
        if (p == e) goto bad;
        long long n = 0;
        for (; p < e; p++) {
            if (*p < '0' || *p > '9') goto bad;
            n = n * 10 + (*p - '0');
        }
        *out = neg ? -n : n;
        return true;
    bad:;
        char *rp = rnf_repr(v);
        char msg[256];
        snprintf(msg, sizeof(msg), "invalid literal for int() with base 10: %s", rp);
        free(rp);
        rnf_raise("ValueError", msg);
        return false;
    }
    char msg[160];
    snprintf(msg, sizeof(msg),
             "int() argument must be a string, a bytes-like object or a real number, not '%s'",
             rnf_typename(v));
    rnf_raise("TypeError", msg);
    return false;
}

/* Deep JSON equality with Python numeric cross-type semantics (True == 1). */
static bool rnf_eq(const json_t *a, const json_t *b) {
    bool an = !a || a->type == JSON_NULL, bn = !b || b->type == JSON_NULL;
    if (an || bn) return an && bn;
    if (rnf_numeric(a) && rnf_numeric(b)) return rnf_numval(a) == rnf_numval(b);
    if (a->type != b->type) return false;
    switch (a->type) {
        case JSON_STRING:
            return strcmp(a->str_val ? a->str_val : "", b->str_val ? b->str_val : "") == 0;
        case JSON_ARRAY: {
            if (a->c.count != b->c.count) return false;
            for (size_t i = 0; i < a->c.count; i++)
                if (!rnf_eq(a->c.items[i], b->c.items[i])) return false;
            return true;
        }
        case JSON_OBJECT: {
            if (a->c.count != b->c.count) return false;
            for (size_t i = 0; i < a->c.count; i++) {
                const json_t *bv = json_obj_get(b, a->c.keys[i]);
                if (!bv || !rnf_eq(a->c.items[i], bv)) return false;
            }
            return true;
        }
        default: return false;
    }
}

/* ── dedup-state helpers (state = {inflight, delivered, retention, lock_held}) ── */

static char *rnf_idkey(const json_t *identity) { return json_serialize(identity); }

static bool rnf_in_set(const json_t *arr, const json_t *id) {
    if (!arr || arr->type != JSON_ARRAY) return false;
    for (size_t i = 0; i < arr->c.count; i++)
        if (rnf_eq(arr->c.items[i], id)) return true;
    return false;
}

static void rnf_set_add(json_t *arr, const json_t *id) {
    if (!rnf_in_set(arr, id)) json_append(arr, json_copy(id));
}

static void rnf_set_discard(json_t *arr, const json_t *id) {
    if (!arr || arr->type != JSON_ARRAY) return;
    for (size_t i = 0; i < arr->c.count; i++) {
        if (rnf_eq(arr->c.items[i], id)) {
            json_free(arr->c.items[i]);
            for (size_t k = i; k + 1 < arr->c.count; k++) arr->c.items[k] = arr->c.items[k + 1];
            arr->c.count--;
            return;
        }
    }
}

/* Elementwise identity compare (fixture identities are all-string tuples). */
static int rnf_id_cmp(const void *pa, const void *pb) {
    const json_t *a = *(json_t *const *)pa, *b = *(json_t *const *)pb;
    size_t n = json_len(a), m = json_len(b), lim = n < m ? n : m;
    for (size_t i = 0; i < lim; i++) {
        const char *sa = gflow_str(json_get(a, i)), *sb = gflow_str(json_get(b, i));
        int c = strcmp(sa ? sa : "", sb ? sb : "");
        if (c) return c;
    }
    return (n > m) - (n < m);
}
/* ── 1. _mark_internal_notification: idempotent machine-provenance footer ── */
/* PoP: rnf_mark_internal_notification @ gateway/run_notifications.py:_mark_internal_notification */
json_t *rnf_mark_internal_notification(const char *text) {
    char *t = rnf_rstrip(text ? text : "");
    size_t flen = sizeof(RNF_INTERNAL_FOOTER) - 1, tlen = strlen(t);
    json_t *ret;
    if (tlen >= flen && strcmp(t + tlen - flen, RNF_INTERNAL_FOOTER) == 0) {
        ret = json_string(t);
    } else {
        size_t n = tlen + 2 + flen + 1;
        char *buf = malloc(n);
        snprintf(buf, n, "%s\n\n%s", t, RNF_INTERNAL_FOOTER);
        ret = json_string(buf);
        free(buf);
    }
    free(t);
    return ret;
}

/* ── 2. _raw_process_event_session_id: API-route recognition gate ── */
/* PoP: rnf_raw_process_event_session_id @ gateway/run_notifications.py:_raw_process_event_session_id */
json_t *rnf_raw_process_event_session_id(const json_t *evt) {
    const json_t *skn = gflow_obj_get(evt, "session_key");
    char *sk_s = gflow_truth(skn) ? gflow_pystr(skn) : strdup("");
    char *session_key = rnf_strip(sk_s);
    free(sk_s);
    const json_t *pln = gflow_obj_get(evt, "platform");
    char *pl_s = gflow_truth(pln) ? gflow_pystr(pln) : strdup("");
    char *pl_t = rnf_strip(pl_s);
    free(pl_s);
    char *platform = rnf_lower(pl_t);
    free(pl_t);
    json_t *ret = NULL;
    if (strncmp(session_key, "agent:", 6) == 0
        || (platform[0] != '\0' && strcmp(platform, "api_server") != 0)) {
        ret = json_string("");
        goto done;
    }
    if (platform[0] == '\0') {
        static const char *fields[3] = { "chat_id", "chat_type", "thread_id" };
        for (int i = 0; i < 3; i++) {
            if (gflow_truth(gflow_obj_get(evt, fields[i]))) {
                ret = json_string("");
                goto done;
            }
        }
    }
    {
        const json_t *osid = gflow_obj_get(evt, "origin_session_id");
        char *raw = gflow_truth(osid) ? gflow_pystr(osid) : strdup(session_key);
        char *final = rnf_strip(raw);
        free(raw);
        ret = json_string(final);
        free(final);
    }
done:
    free(session_key);
    free(platform);
    return ret;
}

