#ifndef PORT_VAULT_LOGIN_CLASSIFIER_H
#define PORT_VAULT_LOGIN_CLASSIFIER_H

#include "hermes_json.h"

/* Port of Python: agent/vault_login_classifier.py — the classification half.
 *
 * Python normalises with unicodedata.normalize("NFKD") + lower + collapse
 * every non-[a-z0-9] run to one space, then runs word-boundary regexes. This
 * port reproduces the same matching over a token sequence, so the patterns are
 * the Python table transcribed as word/pair/triple tests rather than regexes.
 *
 * NFKD decomposition is covered for Latin-1 Supplement (À-ÿ). Latin
 * Extended-A and other scripts fold to separators; Python would decompose
 * those to base letters. Documented, not silently different for ASCII input.
 *
 * NOT ported: build_inspection_js / build_fill_js. They are large JS template
 * literals whose exact bytes (`\\s` escapes, json.dumps spacing) are the
 * contract; they need a dedicated byte-comparison oracle rather than a guess.
 */

typedef struct {
    char *autocomplete;
    int   has_form_index;
    int   form_index;
    int   index;
    char *label;
    char *name;
    char *type;
    int   has_max_length;
    int   max_length;
} vl_control_t;

typedef struct {
    vl_control_t control;
    int  score;
    char *token;
} vl_classified_t;

void vl_control_free(vl_control_t *control);
void vl_classified_free(vl_classified_t *classified);
void vl_classified_list_free(vl_classified_t *list, int n);

/* Build a control from the page inspection JSON object:
 * {autocomplete, formIndex|form_index, index, label, name, type,
 *  maxLength|max_length}. 0 on success, -1 when not an object. */
int vl_control_from_json(const char *json, vl_control_t *out);

/* Python's _normalize_text: NFKD -> lower -> non-alnum to space -> strip. */
char *vl_normalize_text(const char *value);

/* 0 + *out on match; 1 when the control is not a login target. */
int vl_classify_login_control(const vl_control_t *control, vl_classified_t *out);

/* Second-factor controls in DOM order. Returns the count; *out malloc'd. */
int vl_classify_otp_controls(const vl_control_t *controls, int n,
                             vl_classified_t **out);

/* 0 + *out on match; 1 when not a payment/address target. */
int vl_classify_checkout_control(const vl_control_t *control,
                                 vl_classified_t *out);

/* [{"index","token","value"}] for the best current-password control, or []. */
json_t *vl_select_password_fill(const vl_classified_t *classified, int n,
                                const char *password);

/* One fill per token: `secret_json` field values mapped through
 * `field_tokens_json` (field -> token). */
json_t *vl_select_checkout_fills(const vl_classified_t *classified, int n,
                                 const char *secret_json,
                                 const char *field_tokens_json);

/* Per-box fills for a true N-box widget, else the single best field. */
json_t *vl_build_otp_fills(const vl_classified_t *otp, int n, const char *code);

/* The two JS expressions. Generated byte-for-byte from the Python templates by
 * scripts/gen_vault_login_js.py; `fills_json` is the fill list (array of
 * {"index","token","value"}). Both return malloc'd strings. */
char *vl_build_inspection_js(const char *nonce);
char *vl_build_fill_js(const char *fills_json, const char *expected_origin,
                       const char *nonce);

#endif /* PORT_VAULT_LOGIN_CLASSIFIER_H */
