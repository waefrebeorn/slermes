#!/usr/bin/env python3
"""Generate the C11 tables for hermes_cli/observability/shared_metrics_contract.py.

The contract is ~100 KB of literal tables in Python. Re-typing them by hand is
how ports drift, so this emits them straight from the live module:

    src/hermes_cli/shared_metrics_contract_tables.c
    include/shared_metrics_contract_tables.h

Static frozensets are baked in. Catalog-backed enums (`_CatalogValues`) and
per-adapter platform enums (`_AdapterPlatforms`) stay dynamic by design: the
generated accessors take the catalog values the caller loaded, so the seam is
explicit instead of silently frozen.

Run from the repo root with the quarry's venv python:
    C:/Users/eman5/hermes-agent/.venv/Scripts/python.exe scripts/gen_metrics_contract_tables.py
"""
from __future__ import annotations

import os
import sys

Q = "C:/Users/eman5/hermes-agent"
sys.path.insert(0, Q)

from hermes_cli.observability import shared_metrics_contract as C  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = os.path.join(REPO, "include", "shared_metrics_contract_tables.h")
SRC = os.path.join(REPO, "src", "hermes_cli", "shared_metrics_contract_tables.c")


def cstr(s):
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("".join("\\x%02x" % b for b in ch.encode("utf-8")) + '""')
    return '"' + "".join(out) + '"'


def describe(value):
    """(static values, dynamic loaders) for one enum object."""
    name = type(value).__name__
    if name == "frozenset":
        return sorted(value), ()
    if name == "_CatalogValues":
        return sorted(value.extra), tuple(value.loaders)
    if name == "_AdapterPlatforms":
        return sorted(getattr(value, "extra", ())), ("__adapter_platforms__",)
    raise SystemExit("unknown enum container: %r" % (name,))


sets = []          # list of sorted value lists
set_index = {}
loaders = []       # list of (metric, field, tuple(loaders))


def set_id(values):
    key = tuple(values)
    if key not in set_index:
        set_index[key] = len(sets)
        sets.append(list(values))
    return set_index[key]


metrics = sorted(C._METRIC_FIELDS)
legacy = {m: list(C._LEGACY_METRIC_FIELDS.get(m, ())) for m in C._LEGACY_METRIC_FIELDS}
counters = C._COUNTER_DIMENSION_VALUES
ident = C._IDENTIFIER_FIELDS

for metric in sorted(counters):
    for field, value in sorted(counters[metric].items()):
        static, dyn = describe(value)
        set_id(static)
        if dyn:
            loaders.append((metric, field, dyn))

for metric in sorted(legacy):
    for shape in legacy[metric]:
        set_id(sorted(shape))

# metric field sets too -- they are emitted first, so they must exist before the
# array block is written.
for metric in metrics:
    set_id(sorted(C._METRIC_FIELDS[metric]))

lines = []
w = lines.append
w("/* shared_metrics_contract_tables.c -- GENERATED by scripts/gen_metrics_contract_tables.py.")
w(" * Do not edit: regenerate from the live quarry module instead.")
w(' * PoP: smct_metric_fields @ hermes_cli/observability/shared_metrics_contract.py:_METRIC_FIELDS')
w(' * PoP: smct_legacy_shapes @ hermes_cli/observability/shared_metrics_contract.py:_LEGACY_METRIC_FIELDS')
w(' * PoP: smct_counter_allows @ hermes_cli/observability/shared_metrics_contract.py:_COUNTER_DIMENSION_VALUES')
w(' * PoP: smct_identifier_max @ hermes_cli/observability/shared_metrics_contract.py:_IDENTIFIER_FIELDS')
w(' * PoP: smct_metric_identifier @ hermes_cli/observability/shared_metrics_contract.py:_metric_identifier')
w(" */")
w('#include "shared_metrics_contract_tables.h"')
w("")
w("#include <ctype.h>")
w("#include <stdio.h>")
w("#include <string.h>")
w("")

# value arrays
w("/* value sets, deduplicated */")
for i, values in enumerate(sets):
    w("static const char *const SET_%d[] = {%s};" % (i, ", ".join(cstr(v) for v in values) or '""'))
w("")
# (the SET_ arrays are referenced directly by the entry tables; a parallel
# smct_set index array would be dead weight)


# metric -> fields
w("static const struct smct_metric_entry METRIC_FIELDS[] = {")
for metric in metrics:
    fields = sorted(C._METRIC_FIELDS[metric])
    w("    {%s, {SET_%d, %d}, %d}," % (cstr(metric), set_id(fields), len(fields), len(fields)))
w("};")
w("static const size_t METRIC_FIELDS_N = sizeof(METRIC_FIELDS) / sizeof(METRIC_FIELDS[0]);")
w("")

# legacy shapes: metric -> array of set ids
shape_start = {}
for metric in sorted(legacy):
    shape_start[metric] = len(lines)
w("static const struct smct_shape LEGACY_SHAPES[] = {")
for metric in sorted(legacy):
    for shape in legacy[metric]:
        w("    {%s, {SET_%d, %d}, %d}," % (cstr(metric), set_id(sorted(shape)), len(shape), len(shape)))
w("};")
w("static const size_t LEGACY_SHAPES_N = sizeof(LEGACY_SHAPES) / sizeof(LEGACY_SHAPES[0]);")
w("")

# counter enums
w("static const struct smct_field_entry COUNTER_FIELDS[] = {")
for metric in sorted(counters):
    for field, value in sorted(counters[metric].items()):
        static, dyn = describe(value)
        w("    {%s, %s, {SET_%d, %d}, %d}," % (cstr(metric), cstr(field), set_id(static),
                                               len(static), 1 if dyn else 0))
w("};")
w("static const size_t COUNTER_FIELDS_N = sizeof(COUNTER_FIELDS) / sizeof(COUNTER_FIELDS[0]);")
w("")

w("static const struct smct_identifier IDENTIFIERS[] = {")
for metric in sorted(ident):
    for field, maxlen in sorted(ident[metric].items()):
        w("    {%s, %s, %d}," % (cstr(metric), cstr(field), maxlen))
w("};")
w("static const size_t IDENTIFIERS_N = sizeof(IDENTIFIERS) / sizeof(IDENTIFIERS[0]);")
w("")

for name, chars in (("IDENTIFIER_START", C._METRIC_IDENTIFIER_START_CHARACTERS),
                    ("IDENTIFIER_CHARS", C._METRIC_IDENTIFIER_CHARACTERS)):
    table = ["0"] * 256
    for ch in chars:
        table[ord(ch)] = "1"
    w("static const unsigned char %s[256] = {" % name)
    for i in range(0, 256, 16):
        w("    " + ", ".join(table[i:i + 16]) + ",")
    w("};")
    w("")

w("""
static const struct smct_set *find_set_entry(const struct smct_field_entry *rows, size_t n,
                                            const char *metric, const char *field)
{
    size_t i;
    if (!metric || !field) return NULL;
    for (i = 0; i < n; i++) {
        if (!strcmp(rows[i].metric, metric) && !strcmp(rows[i].field, field))
            return &rows[i].set;
    }
    return NULL;
}

const char *const *smct_metric_fields(const char *metric, size_t *n_out)
{
    size_t i;
    if (n_out) *n_out = 0;
    if (!metric) return NULL;
    for (i = 0; i < METRIC_FIELDS_N; i++) {
        if (!strcmp(METRIC_FIELDS[i].name, metric)) {
            if (n_out) *n_out = METRIC_FIELDS[i].set.n;
            return METRIC_FIELDS[i].set.values;
        }
    }
    return NULL;
}

size_t smct_legacy_shape_count(const char *metric)
{
    size_t i, count = 0;
    if (!metric) return 0;
    for (i = 0; i < LEGACY_SHAPES_N; i++)
        if (!strcmp(LEGACY_SHAPES[i].metric, metric)) count++;
    return count;
}

const char *const *smct_legacy_shape(const char *metric, size_t index, size_t *n_out)
{
    size_t i, seen = 0;
    if (n_out) *n_out = 0;
    if (!metric) return NULL;
    for (i = 0; i < LEGACY_SHAPES_N; i++) {
        if (strcmp(LEGACY_SHAPES[i].metric, metric)) continue;
        if (seen++ != index) continue;
        if (n_out) *n_out = LEGACY_SHAPES[i].set.n;
        return LEGACY_SHAPES[i].set.values;
    }
    return NULL;
}

int smct_counter_known(const char *metric, const char *field)
{
    return find_set_entry(COUNTER_FIELDS, COUNTER_FIELDS_N, metric, field) != NULL;
}

int smct_counter_is_dynamic(const char *metric, const char *field)
{
    size_t i;
    if (!metric || !field) return 0;
    for (i = 0; i < COUNTER_FIELDS_N; i++)
        if (!strcmp(COUNTER_FIELDS[i].metric, metric) && !strcmp(COUNTER_FIELDS[i].field, field))
            return COUNTER_FIELDS[i].dynamic;
    return 0;
}

static int list_has(const char *const *values, size_t n, const char *value)
{
    size_t i;
    if (!value) return 0;
    for (i = 0; i < n; i++)
        if (values[i] && !strcmp(values[i], value)) return 1;
    return 0;
}

int smct_counter_allows(const char *metric, const char *field, const char *value,
                       const char *const *dynamic, size_t n_dynamic)
{
    const struct smct_set *set = find_set_entry(COUNTER_FIELDS, COUNTER_FIELDS_N, metric, field);
    if (!set || !value) return 0;
    if (list_has(set->values, set->n, value)) return 1;
    return list_has(dynamic, n_dynamic, value);
}

/* First of custom/other/unknown the field's enum defines, "" when it defines none. */
const char *smct_field_fallback(const char *metric, const char *field)
{
    static const char *const buckets[] = {"custom", "other", "unknown"};
    const struct smct_set *set = find_set_entry(COUNTER_FIELDS, COUNTER_FIELDS_N, metric, field);
    size_t i;
    if (!set) return "";
    for (i = 0; i < sizeof(buckets) / sizeof(buckets[0]); i++)
        if (list_has(set->values, set->n, buckets[i])) return buckets[i];
    return "";
}

int smct_identifier_max(const char *metric, const char *field, int *found)
{
    size_t i;
    if (found) *found = 0;
    if (!metric || !field) return -1;
    for (i = 0; i < IDENTIFIERS_N; i++) {
        if (!strcmp(IDENTIFIERS[i].metric, metric) && !strcmp(IDENTIFIERS[i].field, field)) {
            if (found) *found = 1;
            return IDENTIFIERS[i].max_length;
        }
    }
    return -1;
}

/* UTF-8 aware length, matching Python's len(str). */
static size_t py_str_len(const char *s)
{
    size_t n = 0;
    for (; *s; s++)
        if (((unsigned char)*s & 0xC0) != 0x80) n++;
    return n;
}
""")

w("""
static int identifier_chars_ok(const char *s)
{
    for (; *s; s++)
        if (!IDENTIFIER_CHARS[(unsigned char)*s]) return 0;
    return 1;
}

const char *smct_metric_identifier(const char *value, int max_length, char *buf, size_t cap)
{
    const char *end;
    char *out;
    size_t n = 0, i;

    if (!buf || cap == 0) return "unknown";
    buf[0] = '\\0';
    if (!value) { snprintf(buf, cap, "unknown"); return buf; }

    /* value.strip(): ASCII whitespace both ends (str.strip() also strips unicode
     * spaces; any non-ASCII byte fails the charset check below either way). */
    while (*value && isspace((unsigned char)*value)) value++;
    end = value + strlen(value);
    while (end > value && isspace((unsigned char)end[-1])) end--;
    for (out = buf, i = 0; value + i < end && n + 1 < cap; i++) {
        unsigned char ch = (unsigned char)value[i];
        if (ch >= 'A' && ch <= 'Z') ch = (unsigned char)(ch - 'A' + 'a');
        out[n++] = (char)ch;
    }
    out[n] = '\\0';

    if (n == 0 || (int)py_str_len(buf) > max_length ||
        !IDENTIFIER_START[(unsigned char)buf[0]] || !identifier_chars_ok(buf)) {
        snprintf(buf, cap, "unknown");
        return buf;
    }
    return buf;
}
""")

