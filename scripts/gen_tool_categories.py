#!/usr/bin/env python3
"""Generate src/hermes_cli/tool_categories_data.c from the live Python module.

TOOL_CATEGORIES is a ~9 KB table of provider rows whose values come from `_row`,
`_key`, `_NOUS` and friends -- parsing it as text would mean re-implementing
those helpers and drifting from upstream the moment one changes. So evaluate it
in the real interpreter and emit the RESULT as C data, regenerated by a gate.

Upstream: hermes_cli/tools_config.py::TOOL_CATEGORIES
Run:     python scripts/gen_tool_categories.py
"""
from __future__ import annotations

import importlib
import json
import os
import sys
from pathlib import Path

REPO = Path("C:/Users/eman5/slermes")
QUARRY = Path("C:/Users/eman5/hermes-agent")
OUT = REPO / "src" / "hermes_cli" / "tool_categories_data.c"

HEADER = """/* tool_categories_data.c -- GENERATED by scripts/gen_tool_categories.py.
 * Do not edit by hand; regenerate instead.
 *
 * Upstream: hermes_cli/tools_config.py::TOOL_CATEGORIES, evaluated in the
 * quarry interpreter and emitted verbatim so the C surface cannot drift from
 * the Python one. */
#include "tools_config_providers.h"
"""

PY = QUARRY / ".venv" / "Scripts" / "python.exe"


def load_categories() -> dict:
    sys.path.insert(0, str(QUARRY))
    os.environ.setdefault("HERMES_HOME", str(QUARRY / ".hermes_home_probe"))
    mod = importlib.import_module("hermes_cli.tools_config")
    return mod.TOOL_CATEGORIES


def c_string(s) -> str:
    if not isinstance(s, str):
        s = str(s)
    out = ['"']
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append("\\%03o" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def emit(cats: dict) -> str:
    L = [HEADER]
    L.append("/* ts_key of each category row, in upstream insertion order. */")
    L.append("static const char *const TC_ORDER[] = {")
    for k in cats:
        L.append("    %s," % c_string(k))
    L.append("    NULL")
    L.append("};")
    L.append("")
    L.append("/* One flattened provider row: category index + JSON object. */")
    L.append("typedef struct {")
    L.append("    size_t cat;")
    L.append("    const char *row;")
    L.append("} tc_row_t;")
    L.append("static const tc_row_t TC_ROWS[] = {")
    n = 0
    for ci, (cat, body) in enumerate(cats.items()):
        provs = body.get("providers") or []
        for row in provs:
            L.append("    { %d, %s }," % (ci, c_string(json.dumps(row, ensure_ascii=False))))
            n += 1
    L.append("    { 0, NULL }")
    L.append("};")
    L.append("")
    L.append("/* Category-level fields other than `providers`. */")
    L.append("typedef struct {")
    L.append("    const char *key;")
    L.append("    const char *fields;")
    L.append("} tc_cat_t;")
    L.append("static const tc_cat_t TC_CATS[] = {")
    for cat, body in cats.items():
        rest = {k: v for k, v in body.items() if k != "providers"}
        L.append("    { %s, %s }," % (c_string(cat), c_string(json.dumps(rest, ensure_ascii=False))))
    L.append("    { NULL, NULL }")
    L.append("};")
    L.append("")
    L.append("/* Total provider rows -- used by the generator's own sanity check. */")
    L.append("#define TC_ROW_COUNT %d" % n)
    L.append("")
    L.append("/* Build the TOOL_CATEGORIES document. Fresh each call; caller owns. */")
    L.append("json_t *tool_categories_build(void) {")
    L.append("    json_t *root = json_object();")
    L.append("    for (const tc_cat_t *c = TC_CATS; c->key; c++) {")
    L.append("        char *err = NULL;")
    L.append("        json_t *fields = json_parse(c->fields, &err);")
    L.append("        if (err) { free(err); continue; }")
    L.append("        json_t *arr = json_array();")
    L.append("        for (const tc_row_t *r = TC_ROWS; r->row; r++) {")
    L.append("            if (strcmp(TC_ORDER[r->cat], c->key) != 0) continue;")
    L.append("            char *rerr = NULL;")
    L.append("            json_t *row = json_parse(r->row, &rerr);")
    L.append("            if (rerr) { free(rerr); continue; }")
    L.append("            json_append(arr, row);")
    L.append("        }")
    L.append("        json_set(fields, \"providers\", arr);")
    L.append("        json_set(root, c->key, fields);")
    L.append("    }")
    L.append("    return root;")
    L.append("}")
    L.append("")
    return "\n".join(L)


def main() -> int:
    cats = load_categories()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(emit(cats).encode("utf-8"))
    print("wrote %s: %d categories, %d provider rows" %
          (OUT.name, len(cats), sum(len(b.get("providers") or []) for b in cats.values())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
