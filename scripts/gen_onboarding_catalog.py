#!/usr/bin/env python3
"""Generate src/agent/onboarding_task_catalog_data.c from the Python catalog.

The first-task catalog (13 rows of prose: goal, steps, output, quality, done, skills) is data, and
transcribing prose by hand is how ports acquire silent drift. This reads
session_rules/onboarding_first_tasks.py and emits the table verbatim, so the C side cannot disagree
with the quarry about the words.

Run after the quarry's catalog changes:
    python scripts/gen_onboarding_catalog.py
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

QUARRY = Path(os.environ.get("HERMES_QUARRY", r"C:/Users/eman5/hermes-agent"))
REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(QUARRY))

from session_rules import onboarding_first_tasks as cat  # noqa: E402


def gate_of(task) -> tuple[str, str]:
    """The gate as (kind, arg): kind is one of never|always|plugin|connected|os."""
    fn = task.gate
    name = getattr(fn, "__name__", "")
    if name == "_connected":
        return "connected", ""
    if name == "_always":
        return "always", ""
    if name == "_macos":
        return "os", "macos"
    consts = getattr(getattr(fn, "__code__", None), "co_consts", ())
    if consts and consts[0] is False:
        return "never", ""
    cells = getattr(fn, "__closure__", None) or ()
    for cell in cells:
        try:
            val = cell.cell_contents
        except ValueError:
            continue
        if isinstance(val, str):
            return "plugin", val
    return "never", ""


def cstr(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def cstr_array(items) -> str:
    items = list(items)
    if not items:
        return "{ NULL }"
    parts = ",\n        ".join(cstr(i) for i in items)
    return "{\n        " + parts + ",\n        NULL\n    }"


def main() -> int:
    rows = []
    for task in cat.FIRST_TASKS:
        kind, arg = gate_of(task)
        rows.append(
            "    { %s,\n      %s,\n      ONB_GATE_%s, %s,\n      %s,\n      %s,\n      %s,\n      %s,\n      %s,\n      %s },\n"
            % (
                cstr(task.id), cstr(task.label), kind.upper(), cstr(arg),
                cstr_array(task.skills), cstr(task.goal), cstr_array(task.steps),
                cstr(task.output), cstr(task.quality), cstr(task.done),
            )
        )

    body = """/* GENERATED by scripts/gen_onboarding_catalog.py -- do not edit by hand.
 *
 * Source: session_rules/onboarding_first_tasks.py (FIRST_TASKS, MAX_PICKS, MAX_LABEL, FIXED_ID).
 * Regenerate after the quarry's catalog changes; the oracle compares this table against the module.
 */
#include "onboarding_task_catalog.h"

const int ONB_MAX_PICKS = %d;
const int ONB_MAX_LABEL = %d;
const char *const ONB_FIXED_ID = %s;

const onboarding_task_t ONB_TASKS[] = {
%s    { NULL, NULL, ONB_GATE_NEVER, NULL, { NULL }, NULL, { NULL }, NULL, NULL, NULL }
};

const int ONB_TASK_COUNT = %d;
""" % (cat.MAX_PICKS, cat.MAX_LABEL, cstr(cat.FIXED_ID), "".join(rows), len(cat.FIRST_TASKS))

    own = cat.OWN_TASK
    own_row = ("const onboarding_task_t ONB_OWN_TASK = { %s,\n  %s,\n  ONB_GATE_NEVER, \"\",\n  %s,\n  %s,\n  %s,\n  %s,\n  %s,\n  %s };\n"
               % (cstr(own.id), cstr(own.label), cstr_array(own.skills), cstr(own.goal),
                  cstr_array(own.steps), cstr(own.output), cstr(own.quality), cstr(own.done)))
    body += "\n" + own_row + "\nconst char *const ONB_EVERY_TASK_SKILL = %s;\n" % cstr(cat.EVERY_TASK_SKILL)

    out = REPO / "src" / "agent" / "onboarding_task_catalog_data.c"
    out.write_text(body, encoding="utf-8", newline="")
    print(f"wrote {out.relative_to(REPO)}: {len(cat.FIRST_TASKS)} tasks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
